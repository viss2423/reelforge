<#
.SYNOPSIS
  Starts the ReelForge server automatically at logon (hidden) and opens the firewall for it on
  Private networks only.

.DESCRIPTION
  - Writes a launcher (<data>\autostart\reelforge.cmd) that sets the environment, runs the server
    with Node and restarts it after a crash (a clean exit, e.g. Ctrl+C or shutdown, stops it).
  - Registers the Scheduled Task "ReelForge" for the current user, triggered at logon, running
    without a console window (conhost --headless), with restart-on-failure, no time limit and
    no battery restrictions (the host is usually a laptop).
  - Adds inbound firewall rules (group "ReelForge") for the HTTP and HTTPS ports on the Private
    profile only, plus UDP 5353 when -Mdns is given.
  - Prints the LAN URLs phones should open.

  Run from an elevated PowerShell (firewall rules need administrator rights). -WhatIf shows what
  would happen without changing anything (and works without elevation).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\windows\install-autostart.ps1 -StartNow

.EXAMPLE
  .\install-autostart.ps1 -DataDir D:\ReelForge -HttpsPort 9443 -Mdns
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
  [string]$DataDir = $(if ($env:REELFORGE_DATA) { $env:REELFORGE_DATA } else { Join-Path $env:USERPROFILE '.reelforge' }),
  [ValidateRange(1, 65535)][int]$HttpPort = 8080,
  [ValidateRange(1, 65535)][int]$HttpsPort = 8443,
  [string]$NodePath,
  [string]$RepoRoot = $(Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path,
  [switch]$Mdns,
  [switch]$StartNow
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$TaskName = 'ReelForge'
$RuleGroup = 'ReelForge'
$MinNodeMajor = 26

function Test-Administrator {
  $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
  return (New-Object Security.Principal.WindowsPrincipal $identity).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Get-LanAddresses {
  # Interfaces with a default gateway are the real LAN (what a phone on the same Wi-Fi can
  # reach); host-only adapters (VirtualBox, Hyper-V, WSL) have none.
  $routed = @(Get-NetIPConfiguration -ErrorAction SilentlyContinue |
      Where-Object { $_.IPv4DefaultGateway -and $_.NetAdapter.Status -eq 'Up' } |
      ForEach-Object { $_.IPv4Address.IPAddress })
  if ($routed.Count -gt 0) { return $routed }
  Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object {
      $_.IPAddress -notmatch '^(127\.|169\.254\.)' -and
      $_.InterfaceAlias -notmatch 'vEthernet|VirtualBox|VMware|Loopback|WSL|Docker'
    } |
    Select-Object -ExpandProperty IPAddress
}

# --- Preconditions --------------------------------------------------------------------------
if (-not $WhatIfPreference -and -not (Test-Administrator)) {
  throw 'Run this script from an elevated PowerShell (Run as administrator): firewall rules need it.'
}

$serverDir = Join-Path $RepoRoot 'apps\server'
$entry = Join-Path $serverDir 'src\index.ts'
if (-not (Test-Path $entry)) { throw "ReelForge server not found at $entry (use -RepoRoot)." }

if (-not $NodePath) {
  $cmd = Get-Command node.exe -ErrorAction SilentlyContinue
  if (-not $cmd) { throw 'node.exe not found on PATH. Install Node.js 26 LTS or pass -NodePath.' }
  $NodePath = $cmd.Source
}
if (-not (Test-Path $NodePath)) { throw "Node not found at $NodePath" }
$nodeVersion = (& $NodePath --version).Trim()
if ([int]($nodeVersion.TrimStart('v').Split('.')[0]) -lt $MinNodeMajor) {
  throw "ReelForge needs Node.js $MinNodeMajor+ (found $nodeVersion at $NodePath)."
}

$conhost = Join-Path $env:SystemRoot 'System32\conhost.exe'
$cmdExe = Join-Path $env:SystemRoot 'System32\cmd.exe'

# --- Launcher -------------------------------------------------------------------------------
$autostartDir = Join-Path $DataDir 'autostart'
$logDir = Join-Path $DataDir 'logs'
$launcher = Join-Path $autostartDir 'reelforge.cmd'
$mdnsValue = if ($Mdns) { '1' } else { '0' }

# Restart after a crash (non-zero exit) with a short back-off; a clean exit (0) ends the loop.
$launcherBody = @"
@echo off
rem Generated by scripts\windows\install-autostart.ps1 - re-run that script to change settings.
setlocal
set "NODE_ENV=production"
set "REELFORGE_DATA=$DataDir"
set "HTTP_PORT=$HttpPort"
set "HTTPS_PORT=$HttpsPort"
set "MDNS=$mdnsValue"
cd /d "$serverDir"
:run
rem Keep one 10 MB generation of history so an always-on host never fills the disk with logs.
for %%F in ("$logDir\server.log") do if %%~zF GTR 10485760 move /y "%%~F" "%%~F.1" > nul
"$NodePath" "src\index.ts" >> "$logDir\server.log" 2>&1
if %ERRORLEVEL% EQU 0 goto :eof
echo [%DATE% %TIME%] server exited with %ERRORLEVEL%, restarting in 10 s >> "$logDir\server.log"
rem ping as a sleep: unlike timeout.exe it works without an interactive console.
ping -n 11 127.0.0.1 > nul
goto run
"@

if ($PSCmdlet.ShouldProcess($launcher, 'Write launcher')) {
  New-Item -ItemType Directory -Force -Path $autostartDir, $logDir | Out-Null
  # cmd.exe reads batch files in the OEM code page; ASCII keeps paths intact for typical installs.
  Set-Content -Path $launcher -Value $launcherBody -Encoding ASCII
}

# --- Scheduled Task -------------------------------------------------------------------------
$user = "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute $conhost `
  -Argument "--headless `"$cmdExe`" /d /c `"$launcher`"" -WorkingDirectory $serverDir
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew `
  -RestartCount 5 -RestartInterval (New-TimeSpan -Minutes 1)

if ($PSCmdlet.ShouldProcess($TaskName, 'Register scheduled task (at logon, hidden)')) {
  $task = New-ScheduledTask -Action $action -Trigger $trigger -Principal $principal -Settings $settings `
    -Description 'ReelForge video editor server (installed by scripts\windows\install-autostart.ps1).'
  Register-ScheduledTask -TaskName $TaskName -InputObject $task -Force | Out-Null
}

# --- Firewall (Private profile only) --------------------------------------------------------
$rules = @(
  @{ Name = 'ReelForge-HTTP'; Display = "ReelForge HTTP ($HttpPort)"; Protocol = 'TCP'; Port = $HttpPort },
  @{ Name = 'ReelForge-HTTPS'; Display = "ReelForge HTTPS ($HttpsPort)"; Protocol = 'TCP'; Port = $HttpsPort }
)
if ($Mdns) { $rules += @{ Name = 'ReelForge-mDNS'; Display = 'ReelForge mDNS (5353)'; Protocol = 'UDP'; Port = 5353 } }

if ($PSCmdlet.ShouldProcess("firewall group $RuleGroup", 'Replace inbound rules (Private profile)')) {
  Get-NetFirewallRule -Group $RuleGroup -ErrorAction SilentlyContinue | Remove-NetFirewallRule
  foreach ($r in $rules) {
    New-NetFirewallRule -Name $r.Name -DisplayName $r.Display -Group $RuleGroup `
      -Direction Inbound -Action Allow -Protocol $r.Protocol -LocalPort $r.Port `
      -Profile Private | Out-Null
  }
}

if ($StartNow -and $PSCmdlet.ShouldProcess($TaskName, 'Start now')) {
  Start-ScheduledTask -TaskName $TaskName
}

# --- Summary --------------------------------------------------------------------------------
Write-Host ''
$verb = if ($WhatIfPreference) { 'would be installed (dry run)' } else { 'installed' }
Write-Host "ReelForge autostart $verb (task '$TaskName', user $user)." -ForegroundColor Green
Write-Host "  Node:     $NodePath ($nodeVersion)"
Write-Host "  Data:     $DataDir"
Write-Host "  Logs:     $logDir\server.log"
Write-Host ''
$addresses = @(Get-LanAddresses)
if ($addresses.Count -gt 0) {
  Write-Host 'On your phone (same Wi-Fi), open:' -ForegroundColor Cyan
  Write-Host "  http://$($addresses[0]):$HttpPort   (first time: install the certificate, then pair)"
  foreach ($ip in $addresses) { Write-Host "  https://${ip}:$HttpsPort" }
} else {
  Write-Host 'No LAN IPv4 address found; connect to a network and check http://<this-pc-ip>:8080' -ForegroundColor Yellow
}

$public = @(Get-NetConnectionProfile -ErrorAction SilentlyContinue | Where-Object { $_.NetworkCategory -eq 'Public' })
if ($public.Count -gt 0) {
  Write-Host ''
  Write-Host "Note: '$($public[0].Name)' is a Public network, so the firewall rules do not apply there." -ForegroundColor Yellow
  Write-Host "      If it is your home network: Set-NetConnectionProfile -Name '$($public[0].Name)' -NetworkCategory Private"
}
