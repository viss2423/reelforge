/**
 * Generates the Advanced SubStation Alpha (.ass, v4+) document for all text clips and
 * captions of a project. It is rendered by libass in BOTH places — FFmpeg's `ass` filter on
 * export and JASSUB in the web preview — so what you see is what you export.
 *
 * Rendering model (see ass/*.ts for details)
 * - PlayRes 1080×1920 = canvas px; every event is explicitly positioned and unwrapped
 *   (`\q2`); line breaking and line spacing are computed here, deterministically.
 * - Z-order: tracks later in the array draw on top; each visual element owns three layers
 *   (box, soft shadow, main) at `trackIndex × 3`; captions sit above every track.
 * - Times: every event boundary is rounded through one µs→cs function, so events that touch
 *   in µs touch in the file (no 1 cs gaps/overlaps); `\t`/`\move` offsets are in ms
 *   relative to the rounded event start.
 * - Output is deterministic: styles are named in first-use order and events are sorted by
 *   (start, layer, generation order), which makes the document snapshot-testable.
 *
 * Known renderer limits: libass has no rounded boxes (backgroundRadius is ignored; boxes
 * are BorderStyle 3 per line), and colour emoji render as monochrome glyphs.
 */
import type { AnimationPreset } from './packs.ts'
import type { Project } from './schema.ts'
import { EventSink } from './ass/events.ts'
import { fieldSafe, toCs } from './ass/format.ts'
import { StyleRegistry } from './ass/styles.ts'
import { emitCaptions } from './ass/captions.ts'
import { emitTextClip, resolveAnimations } from './ass/text.ts'

export interface AssContext {
  /** Resolve `<packId>/<animationId>` (or `builtin/<id>`) to an animation preset. */
  resolveAnimation(ref: string): AnimationPreset | undefined
  /** Optional time window (timeline us); events outside are omitted. */
  range?: { start: number; end: number }
}

/** Layers reserved per track (box, shadow, main passes). */
const LAYERS_PER_TRACK = 3

/** Build the complete .ass document for a project. Pure and deterministic. */
export function buildAss(project: Project, ctx: AssContext): string {
  const styles = new StyleRegistry()
  const sink = new EventSink(
    ctx.range ? { start: toCs(ctx.range.start), end: toCs(ctx.range.end) } : undefined,
  )
  project.tracks.forEach((track, trackIndex) => {
    if (track.hidden || track.kind !== 'text') return
    for (const clip of track.clips) {
      if (clip.type !== 'text') continue
      const anims = resolveAnimations(clip, (ref) => ctx.resolveAnimation(ref))
      emitTextClip(clip, anims, trackIndex * LAYERS_PER_TRACK, styles, sink)
    }
  })
  if (project.captions) {
    emitCaptions(project.captions, project.tracks.length * LAYERS_PER_TRACK, styles, sink)
  }

  const info = [
    '[Script Info]',
    '; Generated by ReelForge — edits are overwritten on the next render',
    `Title: ${fieldSafe(project.name)}`,
    'ScriptType: v4.00+',
    'WrapStyle: 0',
    'ScaledBorderAndShadow: yes',
    'YCbCr Matrix: TV.709',
    'PlayResX: 1080',
    'PlayResY: 1920',
  ].join('\n')
  return `${info}\n\n${styles.section()}\n\n${sink.section()}\n`
}
