/**
 * Optional publishing of the live pack to GitHub (PUBLISH_TRENDS=github), free through the
 * owner's existing `gh` login. Uses the Git Data API, so the local checkout the server runs
 * from is never touched:
 *
 *   blobs → one tree on top of the target branch (stale `packs/trending-live/*` removed) →
 *   one commit → fast-forward ref update (never forced).
 *
 * Default mode `pr` commits to a `trends` branch (created from main when missing) and opens
 * a pull request, or leaves the open one to pick up the new commit. Mode `main` fast-forwards
 * main itself. Maintainers run `node scripts/build-packs.mjs` on the PR to index the pack.
 */
import { spawn } from 'node:child_process'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import type { PackManifest } from '@reelforge/core'

export type Exec = (
  cmd: string,
  args: readonly string[],
  input?: string,
) => Promise<{ code: number; stdout: string; stderr: string }>

export const execFile: Exec = (cmd, args, input) =>
  new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] })
    let stdout = ''
    let stderr = ''
    child.stdout.setEncoding('utf8').on('data', (d: string) => (stdout += d))
    child.stderr.setEncoding('utf8').on('data', (d: string) => (stderr += d))
    child.once('error', reject)
    child.once('close', (code) => resolve({ code: code ?? 1, stdout, stderr }))
    child.stdin.end(input ?? '')
  })

export interface PublishOptions {
  /** `owner/name` */
  repo: string
  mode: 'pr' | 'main'
  manifest: PackManifest
  /** Directory holding the pack files. */
  dir: string
  exec?: Exec
  gh?: string
  branch?: string
  base?: string
}

export type PublishResult =
  | { status: 'published'; mode: 'pr' | 'main'; commit: string; prUrl?: string }
  | { status: 'skipped'; reason: string }

const PREFIX = 'packs/trending-live'

export const ghAuthenticated = async (exec: Exec = execFile, gh = 'gh'): Promise<boolean> => {
  try {
    return (await exec(gh, ['auth', 'status'])).code === 0
  } catch {
    return false
  }
}

/** `owner/name` from a GitHub remote URL (https or ssh). */
export const repoFromRemote = (url: string): string | undefined =>
  /github\.com[/:]([^/\s]+\/[^/\s]+?)(?:\.git)?\/?$/.exec(url.trim())?.[1]

export const publishLivePack = async (o: PublishOptions): Promise<PublishResult> => {
  const exec = o.exec ?? execFile
  const gh = o.gh ?? 'gh'
  const base = o.base ?? 'main'
  const branch = o.mode === 'main' ? base : (o.branch ?? 'trends')
  if (!(await ghAuthenticated(exec, gh)))
    return { status: 'skipped', reason: 'gh is not logged in' }

  const api = async <T>(method: string, route: string, body?: unknown): Promise<T> => {
    const args = ['api', '-X', method, `repos/${o.repo}/${route}`]
    if (body !== undefined) args.push('--input', '-')
    const r = await exec(gh, args, body === undefined ? undefined : JSON.stringify(body))
    if (r.code !== 0)
      throw new Error(`gh api ${method} ${route}: ${r.stderr.trim() || r.stdout.trim()}`)
    return (r.stdout.trim() ? JSON.parse(r.stdout) : {}) as T
  }
  const headOf = async (name: string): Promise<string | undefined> => {
    try {
      return (await api<{ object: { sha: string } }>('GET', `git/ref/heads/${name}`)).object.sha
    } catch {
      return undefined
    }
  }

  let head = await headOf(branch)
  if (!head) {
    const main = await headOf(base)
    if (!main) throw new Error(`branch ${base} not found in ${o.repo}`)
    await api('POST', 'git/refs', { ref: `refs/heads/${branch}`, sha: main })
    head = main
  }
  const commit = await api<{ tree: { sha: string } }>('GET', `git/commits/${head}`)
  const tree = await api<{ tree: Array<{ path: string; type: string }> }>(
    'GET',
    `git/trees/${commit.tree.sha}?recursive=1`,
  )

  const files = [...o.manifest.files.map((f) => f.path), 'pack.json']
  const entries: Array<{ path: string; mode: string; type: string; sha: string | null }> = []
  for (const rel of files) {
    const content = await readFile(path.join(o.dir, ...rel.split('/')))
    const blob = await api<{ sha: string }>('POST', 'git/blobs', {
      content: content.toString('base64'),
      encoding: 'base64',
    })
    entries.push({ path: `${PREFIX}/${rel}`, mode: '100644', type: 'blob', sha: blob.sha })
  }
  const keep = new Set(entries.map((e) => e.path))
  for (const e of tree.tree)
    if (e.type === 'blob' && e.path.startsWith(`${PREFIX}/`) && !keep.has(e.path))
      entries.push({ path: e.path, mode: '100644', type: 'blob', sha: null })

  const newTree = await api<{ sha: string }>('POST', 'git/trees', {
    base_tree: commit.tree.sha,
    tree: entries,
  })
  const message = `trends: trending-live ${o.manifest.version}\n\nGenerated by the ReelForge trend engine from public trend signals.`
  const created = await api<{ sha: string }>('POST', 'git/commits', {
    message,
    tree: newTree.sha,
    parents: [head],
  })
  await api('PATCH', `git/refs/heads/${branch}`, { sha: created.sha, force: false })

  if (o.mode === 'main') return { status: 'published', mode: 'main', commit: created.sha }
  const open = await exec(gh, [
    'pr',
    'list',
    '--repo',
    o.repo,
    '--head',
    branch,
    '--state',
    'open',
    '--json',
    'url',
  ])
  const existing =
    open.code === 0 ? (JSON.parse(open.stdout || '[]') as Array<{ url: string }>)[0] : undefined
  if (existing) return { status: 'published', mode: 'pr', commit: created.sha, prUrl: existing.url }
  const pr = await exec(gh, [
    'pr',
    'create',
    '--repo',
    o.repo,
    '--head',
    branch,
    '--base',
    base,
    '--title',
    `Trends: trending-live ${o.manifest.version}`,
    '--body',
    'Daily trend pack generated locally by the ReelForge trend engine (free sources, local LLM).\n\nBefore merging run `node scripts/build-packs.mjs` to add it to `packs/index.json`.',
  ])
  if (pr.code !== 0) throw new Error(`gh pr create: ${pr.stderr.trim()}`)
  return { status: 'published', mode: 'pr', commit: created.sha, prUrl: pr.stdout.trim() }
}
