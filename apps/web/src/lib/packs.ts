/** Helpers over the synced trend packs (`GET /api/packs`). */
import type { TemplatePreset } from '@reelforge/core'
import type { Packs, Trends } from '@/api/schemas.ts'

/** The pack the host's trend engine regenerates daily. */
export const LIVE_PACK = 'trending-live'

export interface TemplateEntry {
  /** `<packId>/<templateId>` — what `POST /api/projects` expects as `templateRef`. */
  ref: string
  packId: string
  template: TemplatePreset
  /** Pack-relative thumbnail path (resolve with `api.packFileUrl`), if any. */
  thumbPath?: string
  /** Sum of slot durations (us). */
  duration: number
  /** Generated by the host from today's trends (the "New today" badge). */
  fresh: boolean
  /** Trend it was generated from ("photo dump", a sound…), for generated templates. */
  trend?: string
}

/**
 * All templates across packs. Templates the host generated from today's trends come first
 * (fresh ones before carried ones), then everything else, most trending first (ties: name).
 */
export const listTemplates = (
  packs: Packs | undefined,
  trends?: Pick<Trends, 'items'>,
): TemplateEntry[] => {
  if (!packs) return []
  const origin = new Map((trends?.items ?? []).map((i) => [i.ref, i]))
  const out: TemplateEntry[] = []
  for (const m of packs.manifests) {
    for (const t of m.templates) {
      const ref = `${m.id}/${t.id}`
      const info = origin.get(ref)
      const live = m.id === LIVE_PACK
      out.push({
        ref,
        packId: m.id,
        template: t,
        ...(t.thumb ? { thumbPath: `${m.id}/${t.thumb}` } : {}),
        duration: t.slots.reduce((sum, s) => sum + s.duration, 0),
        fresh: live && (info ? info.fresh : t.tags.includes('new')),
        ...(info?.trend ? { trend: info.trend } : {}),
      })
    }
  }
  const rank = (e: TemplateEntry) => (e.packId === LIVE_PACK ? (e.fresh ? 2 : 1) : 0)
  return out.sort(
    (a, b) =>
      rank(b) - rank(a) ||
      b.template.trendScore - a.template.trendScore ||
      a.template.name.localeCompare(b.template.name),
  )
}

/** The best template for a topic/vibe: newest generated match first, then any match. */
export const latestMatchingTemplate = (
  templates: readonly TemplateEntry[],
  query: string,
): TemplateEntry | undefined => {
  const words = query
    .toLowerCase()
    .split(/[^\p{L}\p{N}]+/u)
    .filter((w) => w.length > 2)
  const score = (e: TemplateEntry) => {
    const hay =
      `${e.template.name} ${e.template.tags.join(' ')} ${e.template.description} ${e.trend ?? ''}`.toLowerCase()
    return words.filter((w) => hay.includes(w)).length
  }
  let best: TemplateEntry | undefined
  let bestScore = 0
  for (const e of templates) {
    const s = score(e)
    if (s > bestScore) {
      best = e
      bestScore = s
    }
  }
  return best ?? templates[0]
}

/** Font faces shipped in packs, for the preview engine's text renderer. */
export const packFonts = (
  packs: Packs | undefined,
  fileUrl: (path: string) => string,
): { family: string; url: string }[] =>
  packs?.index.fonts.flatMap((f) =>
    f.files.map((file) => ({ family: f.family, url: fileUrl(file.path) })),
  ) ?? []
